#!/bin/bash
# Copies a set of Debian's dynamically linked programs and the shared
# libraries they need from this machine's Debian into assets/userspace and
# writes kernel/src/initramfs_gnu.rs, which embeds them. Run it from WSL:
#   wsl -d Debian -- bash tools/make-gnu-userspace.sh /mnt/c/Users/<you>/AerOS
set -e
root="${1:-.}"
assets="$root/assets/userspace"
programs="bash ls cat echo head tail wc sort uniq cut tr date env pwd mkdir cp mv rm ln chmod stat du df basename dirname tee seq sleep true false id uname printf expr grep sed gzip diff find xargs readlink touch mktemp realpath od base64 dd rmdir tac nl comm paste fold join split sum tty whoami tar less make mawk patch cmp xz bzip2 git kill hostname nano vim.tiny"
mkdir -p "$assets/gnu" "$assets/lib"
libs=""
out="$root/kernel/src/initramfs_gnu.rs"
{
  echo "//! Generated by tools/make-gnu-userspace.sh: Debian's dynamically linked"
  echo "//! programs and the shared libraries they need."
  echo "use crate::vfs::InitramfsEntry;"
  echo
  echo "static BASH: &[u8] = include_bytes!(\"../../assets/userspace/gnu/bash\");"
  echo
} > "$out"
entries=""
count=0
for name in $programs; do
  path=""; for dir in /usr/bin /bin /usr/sbin; do [ -x "$dir/$name" ] && { path="$dir/$name"; break; }; done
  [ -n "$path" ] || { echo "skipping $name (not found)" >&2; continue; }
  real="$(readlink -f "$path")"
  head -c 4 "$real" | grep -q ELF || { echo "skipping $name (not ELF)" >&2; continue; }
  cp -L "$real" "$assets/gnu/$name"
  for lib in $(ldd "$real" | awk '/=>/ {print $3}'); do
    case " $libs " in *" $lib "*) ;; *) libs="$libs $lib" ;; esac
  done
  if [ "$name" = bash ]; then
    data="BASH"
  else
    data="include_bytes!(\"../../assets/userspace/gnu/$name\")"
  fi
  entries="$entries
    InitramfsEntry {
        path: \"/bin/$name\",
        data: $data,
        mode: 0o555,
    },"
  count=$((count + 1))
done
# Programs that go by another name too.
for alias in "mawk awk" "vim.tiny vi"; do
  set -- $alias
  [ -f "$assets/gnu/$1" ] || continue
  entries="$entries
    InitramfsEntry {
        path: \"/bin/$2\",
        data: include_bytes!(\"../../assets/userspace/gnu/$1\"),
        mode: 0o555,
    },"
  count=$((count + 1))
done
# bash is also /bin/sh (system(), popen() and scripts run it).
entries="$entries
    InitramfsEntry {
        path: \"/bin/sh\",
        data: BASH,
        mode: 0o555,
    },"
count=$((count + 1))
for lib in $libs; do
  soname="$(basename "$lib")"
  [ "$soname" = "libc.so.6" ] && continue
  cp -L "$lib" "$assets/lib/$soname"
  entries="$entries
    InitramfsEntry {
        path: \"/lib/x86_64-linux-gnu/$soname\",
        data: include_bytes!(\"../../assets/userspace/lib/$soname\"),
        mode: 0o555,
    },"
  count=$((count + 1))
done
{
  echo "pub static GNU: [InitramfsEntry; $count] = [$entries"
  echo "];"
} >> "$out"
echo "wrote $out with $count entries"
du -sh "$assets/gnu" "$assets/lib"
