"""Compiles kernel/linux/gpu/*.c for the laptop's Radeon (GFX9, gfx90c) with
the clang inside Zig and writes kernel/linux/drivers/aeros_gpu_kernels.h: each
kernel's machine code and its COMPUTE_PGM_RSRC1/RSRC2 values from the kernel
descriptor, for aeros_gpu.c to dispatch.

    python tools/gpu-kernels.py
"""
import pathlib
import struct
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ZIG = ROOT / "build/gpu/zig-x86_64-windows-0.17.0/zig.exe"
SOURCE = ROOT / "kernel/linux/gpu"
OUT = ROOT / "kernel/linux/drivers/aeros_gpu_kernels.h"


def sections(data):
    shoff, = struct.unpack_from("<Q", data, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", data, 0x3A)
    table = []
    for index in range(shnum):
        base = shoff + index * shentsize
        name, kind, _, _, offset, size, link, _, _, entsize = struct.unpack_from("<IIQQQQIIQQ", data, base)
        table.append(dict(name=name, kind=kind, offset=offset, size=size, link=link, entsize=entsize))
    names = table[shstrndx]
    for section in table:
        end = data.index(b"\0", names["offset"] + section["name"])
        section["name"] = data[names["offset"] + section["name"]:end].decode()
    return table


def symbols(data, table):
    symtab = next(s for s in table if s["kind"] == 2)
    strtab = table[symtab["link"]]
    found = {}
    for base in range(symtab["offset"], symtab["offset"] + symtab["size"], 24):
        name, info, _, shndx, value, size = struct.unpack_from("<IBBHQQ", data, base)
        end = data.index(b"\0", strtab["offset"] + name)
        found[data[strtab["offset"] + name:end].decode()] = (shndx, value, size)
    return found


def main():
    lines = ["/* Generated by tools/gpu-kernels.py from kernel/linux/gpu: do not edit. */", "#pragma once", ""]
    for source in sorted(SOURCE.glob("*.c")):
        obj = source.with_suffix(".o")
        subprocess.run([str(ZIG), "clang", "--target=amdgcn-amd-amdhsa", "-mcpu=gfx90c", "-O3",
                        "-nostdlib", "-ffreestanding", "-c", str(source), "-o", str(obj)], check=True)
        data = obj.read_bytes()
        table = sections(data)
        found = symbols(data, table)
        if any(s["kind"] in (4, 9) and ".text" in s["name"] for s in table):
            sys.exit(f"{source.name}: the code needs relocations; keep kernels self-contained")
        for name, (shndx, value, size) in found.items():
            if not name.endswith(".kd") or name[:-3] not in found:
                continue
            kernel = name[:-3]
            kd_section = table[shndx]
            rsrc1, rsrc2 = struct.unpack_from("<II", data, kd_section["offset"] + value + 48)
            code_shndx, code_value, code_size = found[kernel]
            text = table[code_shndx]
            code = data[text["offset"] + code_value:text["offset"] + code_value + code_size]
            code += b"\0" * (-len(code) % 4)
            words = struct.unpack(f"<{len(code) // 4}I", code)
            lines.append(f"static const u32 aeros_gpu_{kernel}_code[] = {{")
            for start in range(0, len(words), 6):
                lines.append("\t" + ", ".join(f"0x{w:08x}" for w in words[start:start + 6]) + ",")
            lines.append("};")
            lines.append(f"#define AEROS_GPU_{kernel.upper()}_RSRC1 0x{rsrc1:08x}u")
            lines.append(f"#define AEROS_GPU_{kernel.upper()}_RSRC2 0x{rsrc2:08x}u")
            lines.append("")
            print(f"{kernel}: {len(words)} words, rsrc1 {rsrc1:#x} rsrc2 {rsrc2:#x}")
        obj.unlink()
    OUT.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
