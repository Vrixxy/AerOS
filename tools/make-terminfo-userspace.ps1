param(
    # Debian's root filesystem image (the Linux guest's), read with 7-Zip.
    [string]$RootFs = (Join-Path $PSScriptRoot "..\build\esp\ROOTFS"),
    [string]$SevenZip = "C:\Program Files\7-Zip\7z.exe"
)

# The terminfo entries Terminal programs look up by $TERM (ncurses: nano,
# less, Python's curses; the Terminal's jobs get TERM=vt100), copied to
# assets\userspace\terminfo and listed in kernel\src\initramfs_terminfo.rs.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$assets = Join-Path $root "assets\userspace\terminfo"
$names = @("a/ansi", "d/dumb", "l/linux", "v/vt100", "v/vt102", "v/vt220", "x/xterm")
$staging = Join-Path ([IO.Path]::GetTempPath()) ("aeros-terminfo-" + [guid]::NewGuid())
try {
    $wanted = $names | ForEach-Object { "usr\share\terminfo\" + ($_ -replace '/', '\') }
    & $SevenZip x $RootFs "-o$staging" @wanted -y 2>&1 | Out-Null
    if (Test-Path -LiteralPath $assets) {
        Remove-Item -Recurse -Force -LiteralPath $assets
    }
    $entries = foreach ($name in $names) {
        $source = Join-Path $staging ("usr\share\terminfo\" + ($name -replace '/', '\'))
        if (-not (Test-Path -LiteralPath $source)) {
            throw "terminfo entry $name is not in $RootFs"
        }
        $target = Join-Path $assets ($name -replace '/', '\')
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $target) | Out-Null
        Copy-Item -LiteralPath $source -Destination $target
        "    InitramfsEntry {`n        path: `"/usr/share/terminfo/$name`",`n        data: include_bytes!(`"../../assets/userspace/terminfo/$name`"),`n        mode: 0o444,`n    },"
    }
    $source = @(
        "//! Generated by tools/make-terminfo-userspace.ps1: the terminfo entries",
        "//! for the terminals the Terminal's programs are told they run on.",
        "use crate::vfs::InitramfsEntry;",
        "",
        "pub static TERMINFO_FILES: [InitramfsEntry; $($names.Count)] = ["
    ) + $entries + @("];", "")
    $output = Join-Path $root "kernel\src\initramfs_terminfo.rs"
    [IO.File]::WriteAllText($output, ($source -join "`n"))
    & rustfmt --edition 2024 $output
    "terminfo entries=$($names.Count)"
} finally {
    Remove-Item -Recurse -Force $staging -ErrorAction SilentlyContinue
}
