#!/bin/bash
# Copies Debian's Perl (the interpreter and perl-base: the modules and XS
# libraries a script needs without installing more) from this machine's
# Debian into assets/userspace/perl and writes kernel/src/initramfs_perl.rs,
# which embeds them. Run it from WSL:
#   wsl -d Debian -- bash tools/make-perl-userspace.sh /mnt/c/Users/<you>/AerOS
set -e
root="${1:-.}"
assets="$root/assets/userspace/perl"
base=/usr/lib/x86_64-linux-gnu/perl-base
rm -rf "$assets"
mkdir -p "$assets" "$root/assets/userspace/lib"
cp -L "$(readlink -f /usr/bin/perl)" "$assets/perl"
libs=""
files="$(cd "$base" && find . -type f \( -name '*.pm' -o -name '*.so' -o -name '*.pl' \) ! -path './unicore/*' ! -name 'Config_git.pl' | sed 's|^\./||' | sort)"
for file in $files; do
  mkdir -p "$assets/base/$(dirname "$file")"
  cp -L "$base/$file" "$assets/base/$file"
done
for file in "$assets/perl" $(find "$assets/base" -name '*.so'); do
  for lib in $(ldd "$file" | awk '/=>/ {print $3}'); do
    case " $libs " in *" $lib "*) ;; *) libs="$libs $lib" ;; esac
  done
done
out="$root/kernel/src/initramfs_perl.rs"
{
  echo "//! Generated by tools/make-perl-userspace.sh: Debian's Perl and perl-base."
  echo "use crate::vfs::InitramfsEntry;"
  echo
  echo "static PERL: &[u8] = include_bytes!(\"../../assets/userspace/perl/perl\");"
  echo
} > "$out"
entries="
    InitramfsEntry {
        path: \"/usr/bin/perl\",
        data: PERL,
        mode: 0o555,
    },"
count=1
for file in $files; do
  entries="$entries
    InitramfsEntry {
        path: \"$base/$file\",
        data: include_bytes!(\"../../assets/userspace/perl/base/$file\"),
        mode: 0o444,
    },"
  count=$((count + 1))
done
for lib in $libs; do
  soname="$(basename "$lib")"
  case "$soname" in libc.so.6|libm.so.6) continue ;; esac
  cp -L "$lib" "$root/assets/userspace/lib/$soname"
  entries="$entries
    InitramfsEntry {
        path: \"/lib/x86_64-linux-gnu/$soname\",
        data: include_bytes!(\"../../assets/userspace/lib/$soname\"),
        mode: 0o555,
    },"
  count=$((count + 1))
done
{
  echo "pub static PERL_FILES: [InitramfsEntry; $count] = [$entries"
  echo "];"
} >> "$out"
echo "wrote $out with $count entries"
du -sh "$assets"
