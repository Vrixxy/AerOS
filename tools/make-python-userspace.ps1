# Extracts Debian's Python 3.13 (from the Linux guest's root filesystem image,
# build\esp\ROOTFS) into assets\userspace\python and writes
# kernel\src\initramfs_python.rs, which embeds it in the initramfs.
# Needs 7-Zip. Byte-code caches, tests, Tk, IDLE and extension modules whose
# libraries are not in the initramfs are left out.
param(
    [string]$RootFs = (Join-Path $PSScriptRoot "..\build\esp\ROOTFS"),
    [string]$SevenZip = "C:\Program Files\7-Zip\7z.exe"
)
$ErrorActionPreference = "Stop"
$root = Resolve-Path (Join-Path $PSScriptRoot "..")
$assets = Join-Path $root "assets\userspace\python"
$staging = Join-Path ([IO.Path]::GetTempPath()) ("aeros-python-" + [Guid]::NewGuid())
New-Item -ItemType Directory -Force $staging | Out-Null
# The libraries the interpreter and its extension modules need that the
# initramfs does not already have (libc, libm, libz, libbz2, liblzma, libtinfo
# and libncursesw are there): (file in the image, name it is loaded by).
$libraries = @(
    @("libexpat.so.1.12.3", "libexpat.so.1"),
    @("libffi.so.8.1.4", "libffi.so.8"),
    @("libssl.so.3", "libssl.so.3"),
    @("libcrypto.so.3", "libcrypto.so.3"),
    @("libzstd.so.1.5.7", "libzstd.so.1"),
    @("libsqlite3.so.0.8.6", "libsqlite3.so.0"),
    @("libreadline.so.8.2", "libreadline.so.8"),
    @("libpanelw.so.6.5", "libpanelw.so.6"),
    @("libuuid.so.1.3.0", "libuuid.so.1")
)
try {
    $wanted = @("usr\bin\python3.13", "usr\lib\python3.13\*", "etc\ssl\certs\ca-certificates.crt") +
        ($libraries | ForEach-Object { "usr\lib\x86_64-linux-gnu\" + $_[0] })
    $ErrorActionPreference = "Continue"
    & $SevenZip x $RootFs "-o$staging" @wanted -r -y 2>&1 | Out-Null
    $ErrorActionPreference = "Stop"
    # 2: some symbolic links could not be made (sitecustomize.py, the
    # sysconfig data); everything else is there.
    if ($LASTEXITCODE -gt 2) { throw "7-Zip failed ($LASTEXITCODE)" }
    $skip = '[\\/](__pycache__|test|tests|idle_test|pydoc_data|idlelib|tkinter|turtledemo|ensurepip|lib2to3|_pyrepl|venv|config-3\.13[^\\/]*)[\\/]|turtle\.py$|\.exe$|^LICENSE\.txt$|lib-dynload[\\/](_test|xx|_ctypes_test|_codecs_(cn|hk|jp|kr|tw|iso2022)|_dbm)'
    if (Test-Path $assets) { Remove-Item -Recurse -Force $assets }
    New-Item -ItemType Directory -Force $assets | Out-Null
    $entries = New-Object System.Collections.Generic.List[string]
    $add = {
        param([string]$source, [string]$target, [string]$mode)
        $relative = $target.TrimStart('/') -replace '/', '\'
        $destination = Join-Path $assets $relative
        New-Item -ItemType Directory -Force (Split-Path $destination) | Out-Null
        Copy-Item -LiteralPath $source -Destination $destination
        $include = "../../assets/userspace/python/" + $target.TrimStart('/')
        $entries.Add("    InitramfsEntry {`n        path: `"$target`",`n        data: include_bytes!(`"$include`"),`n        mode: $mode,`n    },")
    }
    & $add (Join-Path $staging "usr\bin\python3.13") "/usr/bin/python3.13" "0o555"
    foreach ($library in $libraries) {
        & $add (Join-Path $staging ("usr\lib\x86_64-linux-gnu\" + $library[0])) ("/lib/x86_64-linux-gnu/" + $library[1]) "0o444"
    }
    & $add (Join-Path $staging "etc\ssl\certs\ca-certificates.crt") "/etc/ssl/certs/ca-certificates.crt" "0o444"
    # OpenSSL's default CA file (a symbolic link to the bundle on Debian).
    $entries.Add("    InitramfsEntry {`n        path: `"/usr/lib/ssl/cert.pem`",`n        data: include_bytes!(`"../../assets/userspace/python/etc/ssl/certs/ca-certificates.crt`"),`n        mode: 0o444,`n    },")
    $library = Join-Path $staging "usr\lib\python3.13"
    Get-ChildItem -LiteralPath $library -Recurse -File | Sort-Object FullName | ForEach-Object {
        $relative = $_.FullName.Substring($library.Length + 1)
        if ($relative -match $skip -or ("\" + $relative) -match $skip) { return }
        # Symbolic links come out as tiny text files naming their target.
        if ($_.Length -lt 64 -and $relative -notmatch '\.py$') { return }
        & $add $_.FullName ("/usr/lib/python3.13/" + ($relative -replace '\\', '/')) "0o444"
    }
    $count = $entries.Count + 1
    $source = @(
        "//! Generated by tools/make-python-userspace.ps1: Debian's Python 3.13.",
        "use crate::vfs::InitramfsEntry;",
        "",
        "static PYTHON: &[u8] = include_bytes!(`"../../assets/userspace/python/usr/bin/python3.13`");",
        "",
        "pub static PYTHON_FILES: [InitramfsEntry; $count] = [",
        "    InitramfsEntry {`n        path: `"/usr/bin/python3`",`n        data: PYTHON,`n        mode: 0o555,`n    },"
    ) + ($entries | ForEach-Object { $_ -replace 'include_bytes!\("\.\./\.\./assets/userspace/python/usr/bin/python3\.13"\)', 'PYTHON' }) + @("];", "")
    [IO.File]::WriteAllText((Join-Path $root "kernel\src\initramfs_python.rs"), ($source -join "`n"))
    # CI checks formatting, and long paths wrap differently than written here.
    & rustfmt --edition 2024 (Join-Path $root "kernel\src\initramfs_python.rs")
    $bytes = (Get-ChildItem -LiteralPath $assets -Recurse -File | Measure-Object Length -Sum).Sum
    "python files=$count bytes=$bytes"
} finally {
    Remove-Item -Recurse -Force $staging -ErrorAction SilentlyContinue
}
